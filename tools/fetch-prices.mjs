// Price snapshot generator: pulls Grand Exchange prices from the OSRS Wiki real-time prices API once and writes
// data/prices.js, which the page loads locally — visitors never call the API.
// Usage: node tools/fetch-prices.mjs [index.html] [out.js]     (3 requests: /mapping, /24h, /latest)
// Price = midpoint of the 24h average high/low (falls back to the latest high/low). Items the GE doesn't list
// (untradeable, e.g. Desiccated page) are written as 0.
import fs from 'node:fs';
import path from 'node:path';

const htmlPath = process.argv[2] || 'index.html';
const outPath = process.argv[3] || path.join(path.dirname(htmlPath), 'data', 'prices.js');
const API = 'https://prices.runescape.wiki/api/v1/osrs';
const UA = 'fractured-archive-loot-simulator/1.0 (price snapshot; https://github.com/ghoulboards/osrs-fractured-archive-loot-simulator)';

// Item lists come straight from the page so nothing drifts.
const html = fs.readFileSync(htmlPath, 'utf8');
const start = html.indexOf('const teamDenom'), end = html.indexOf('const allItems');
if (start < 0 || end < 0) throw new Error('could not find item tables in ' + htmlPath);
const { uniques, standard } = new Function(html.slice(start, end) + '; return {uniques,standard};')();
const names = [...uniques, ...standard].map(i => i.name);

async function get(endpoint) {
  const res = await fetch(`${API}/${endpoint}`, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${endpoint}: HTTP ${res.status}`);
  return res.json();
}
const mapping = await get('mapping');
const day = (await get('24h')).data;
const latest = (await get('latest')).data;

const byName = new Map(mapping.map(m => [m.name.toLowerCase(), m]));
const mid = (a, b) => (a && b ? Math.round((a + b) / 2) : a || b || null);
const prices = {}, untradeable = [], noData = [];
for (const name of names) {
  const m = byName.get(name.toLowerCase());
  if (!m) { prices[name] = 0; untradeable.push(name); continue; }
  const d = day[m.id] || {}, l = latest[m.id] || {};
  const p = mid(d.avgHighPrice, d.avgLowPrice) ?? mid(l.high, l.low);
  if (p == null) { noData.push(name); continue; } // keep the page's built-in fallback price
  prices[name] = p;
}

const updated = new Date().toISOString().slice(0, 10);
const body = `// Generated by tools/fetch-prices.mjs on ${updated} from the OSRS Wiki real-time prices API
// (https://prices.runescape.wiki), midpoint of the 24h average high/low. Do not edit by hand; re-run the script.
window.PRICE_SNAPSHOT = ${JSON.stringify({ updated, source: 'OSRS Wiki real-time prices (24h average)', prices }, null, 1)};
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, body);
const fmt = n => n >= 1e9 ? (n / 1e9).toFixed(2) + 'B' : n >= 1e6 ? (n / 1e6).toFixed(2) + 'M' : n >= 1e3 ? (n / 1e3).toFixed(1) + 'K' : String(n);
for (const u of uniques) console.log(`${u.name.padEnd(28)} ${fmt(prices[u.name] ?? u.price).padStart(9)}`);
console.log(`\nWrote ${outPath}: ${Object.keys(prices).length} prices as of ${updated}.`);
if (untradeable.length) console.log(`Untradeable (0 GP): ${untradeable.join(', ')}`);
if (noData.length) console.log(`No recent trades (kept built-in price): ${noData.join(', ')}`);
